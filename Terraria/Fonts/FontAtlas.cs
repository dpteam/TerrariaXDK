using System;
using System.Collections.Generic;
using System.Globalization;
using System.Reflection;
using System.Text;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Terraria.Fonts;

/// <summary>
/// A font atlas described by a text file: one texture plus the metrics the game needs to draw
/// with it.
///
/// Why this exists: the five built-in translations have their glyphs baked into
/// <c>Content/Fonts/HD</c> as atlases whose character list is compiled into <see cref="FontHD"/>.
/// That is why the game cannot show Cyrillic, Greek or anything else - there is no glyph for it,
/// and there is no way to add one without a new build. A language whose glyphs are not baked in
/// gets them from <c>Storage/Fonts/</c> instead, generated by <c>tools/FontAtlas</c> from any
/// TrueType font the player has.
///
/// The format is deliberately plain text with decimal numbers: it is meant to be generated, read
/// and debugged by hand when something looks wrong. The alternative - a binary blob - would save
/// a few kilobytes and make every alignment bug a hex dump.
///
/// The convention matches the baked atlases exactly (see <c>FontHDBig.BigBounds</c>): every glyph
/// is a cell of <c>advance x lineHeight</c>, drawn at the pen position, so
/// <c>cropping = (0, 0, advance, lineHeight)</c> and <c>kerning = (0, advance, 0)</c>. That is
/// not the tight-cropping convention of the XNA content pipeline, and using that one here would
/// draw every glyph in the wrong place.
/// </summary>
internal sealed class FontAtlas
{
	internal const string Magic = "TerrariaXDK-font-atlas";

	internal const int Version = 1;

	/// <summary>Texture file, relative to the metrics file.</summary>
	public string TexturePath = "";

	public int LineHeight = 1;

	public float Spacing;

	/// <summary>Drawn in place of a character the atlas does not have.</summary>
	public char? DefaultCharacter;

	public readonly List<char> Characters = new List<char>();

	public readonly List<Rectangle> GlyphBounds = new List<Rectangle>();

	public readonly List<Rectangle> Cropping = new List<Rectangle>();

	public readonly List<Vector3> Kerning = new List<Vector3>();

	public int Count => Characters.Count;

	public bool Has(char c)
	{
		return Characters.Contains(c);
	}

	/// <summary>
	/// Adds one glyph. The cell convention is applied here rather than at each call site, so a
	/// caller cannot build an atlas that draws correctly in the generator and wrongly in the game.
	/// </summary>
	public void Add(char c, int advance, int x, int y)
	{
		if (advance <= 0)
		{
			advance = 1;
		}
		Characters.Add(c);
		GlyphBounds.Add(new Rectangle(x, y, advance, LineHeight));
		Cropping.Add(new Rectangle(0, 0, advance, LineHeight));
		Kerning.Add(new Vector3(0f, advance, 0f));
	}

	public string Format()
	{
		StringBuilder stringBuilder = new StringBuilder();
		stringBuilder.Append("# ").Append(Magic).Append(' ').Append(Version.ToString(CultureInfo.InvariantCulture)).Append('\n');
		stringBuilder.Append("# texture, then lineHeight, spacing and the fallback character\n");
		stringBuilder.Append("texture=").Append(TexturePath).Append('\n');
		stringBuilder.Append("lineHeight=").Append(LineHeight.ToString(CultureInfo.InvariantCulture)).Append('\n');
		stringBuilder.Append("spacing=").Append(Spacing.ToString("0.###", CultureInfo.InvariantCulture)).Append('\n');
		stringBuilder.Append("default=").Append(DefaultCharacter.HasValue
			? ((int)DefaultCharacter.Value).ToString(CultureInfo.InvariantCulture)
			: "-1").Append('\n');
		stringBuilder.Append("# codepoint advance x y  - one line per glyph\n");
		stringBuilder.Append("glyphs=").Append(Characters.Count.ToString(CultureInfo.InvariantCulture)).Append('\n');
		for (int i = 0; i < Characters.Count; i++)
		{
			stringBuilder.Append(((int)Characters[i]).ToString(CultureInfo.InvariantCulture)).Append(' ')
				.Append(GlyphBounds[i].Width.ToString(CultureInfo.InvariantCulture)).Append(' ')
				.Append(GlyphBounds[i].X.ToString(CultureInfo.InvariantCulture)).Append(' ')
				.Append(GlyphBounds[i].Y.ToString(CultureInfo.InvariantCulture)).Append('\n');
		}
		return stringBuilder.ToString();
	}

	/// <summary>
	/// Builds the <see cref="SpriteFont"/> the renderer expects. The constructor is not public in
	/// this build, which is why it is reached by reflection here exactly as
	/// <c>UI.BuildFonts</c> does for the baked atlases - same signature, same meaning.
	/// </summary>
	internal static SpriteFont BuildSpriteFont(Texture2D texture, FontAtlas atlas)
	{
		ConstructorInfo constructor = typeof(SpriteFont).GetConstructor(
			BindingFlags.Instance | BindingFlags.NonPublic, null,
			new Type[8]
			{
				typeof(Texture2D), typeof(List<Rectangle>), typeof(List<Rectangle>), typeof(List<char>),
				typeof(int), typeof(float), typeof(List<Vector3>), typeof(char?)
			}, null);
		if (constructor == null)
		{
			throw new InvalidOperationException("SpriteFont has no internal constructor to build from");
		}
		object[] parameters = new object[8]
		{
			texture, atlas.GlyphBounds, atlas.Cropping, atlas.Characters,
			atlas.LineHeight, atlas.Spacing, atlas.Kerning, atlas.DefaultCharacter
		};
		return (SpriteFont)constructor.Invoke(parameters);
	}

	/// <summary>Reads the format above. Returns null with a reason for anything malformed.</summary>
	internal static FontAtlas Parse(string text, out string error)
	{
		error = null;
		if (string.IsNullOrEmpty(text))
		{
			error = "the metrics file is empty";
			return null;
		}
		FontAtlas fontAtlas = new FontAtlas();
		int num = 0;
		bool flag = false;
		int num2 = -1;
		string[] array = text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
		for (int i = 0; i < array.Length; i++)
		{
			string text2 = array[i].Trim();
			if (text2.Length == 0 || text2[0] == '#')
			{
				continue;
			}
			int num3 = text2.IndexOf('=');
			if (num3 > 0)
			{
				string text3 = text2.Substring(0, num3).Trim();
				string text4 = text2.Substring(num3 + 1).Trim();
				switch (text3.ToLowerInvariant())
				{
				case "texture":
					fontAtlas.TexturePath = text4;
					break;
				case "lineheight":
					if (!int.TryParse(text4, NumberStyles.Integer, CultureInfo.InvariantCulture, out fontAtlas.LineHeight) || fontAtlas.LineHeight <= 0)
					{
						error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": lineHeight must be a positive number";
						return null;
					}
					break;
				case "spacing":
					if (!float.TryParse(text4, NumberStyles.Float, CultureInfo.InvariantCulture, out fontAtlas.Spacing))
					{
						error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": spacing is not a number";
						return null;
					}
					break;
				case "default":
					if (!int.TryParse(text4, NumberStyles.Integer, CultureInfo.InvariantCulture, out num2))
					{
						error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": default is not a number";
						return null;
					}
					break;
				case "glyphs":
					if (!int.TryParse(text4, NumberStyles.Integer, CultureInfo.InvariantCulture, out num) || num < 0)
					{
						error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": glyphs is not a count";
						return null;
					}
					flag = true;
					break;
				default:
					// An unknown key is a typo or a newer format. Ignoring it is right; failing
					// would make a harmless addition break every older file.
					break;
				}
				continue;
			}
			if (!flag)
			{
				error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": glyph data before the glyphs= line";
				return null;
			}
			if (!ParseGlyph(text2, fontAtlas, out error))
			{
				error = "line " + (i + 1).ToString(CultureInfo.InvariantCulture) + ": " + error;
				return null;
			}
		}
		if (fontAtlas.TexturePath.Length == 0)
		{
			error = "the metrics file does not name a texture";
			return null;
		}
		if (!flag)
		{
			error = "the metrics file has no glyphs= line";
			return null;
		}
		if (fontAtlas.Characters.Count != num)
		{
			error = "the file says " + num.ToString(CultureInfo.InvariantCulture) + " glyph(s) but has "
				+ fontAtlas.Characters.Count.ToString(CultureInfo.InvariantCulture);
			return null;
		}
		if (fontAtlas.Characters.Count == 0)
		{
			error = "the atlas has no glyphs";
			return null;
		}
		if (num2 >= 0)
		{
			// The fallback has to be a character the atlas actually has, or MeasureString throws
			// the moment a string contains anything unexpected.
			char value = (char)num2;
			if (!fontAtlas.Has(value))
			{
				error = "the default character (codepoint " + num2.ToString(CultureInfo.InvariantCulture)
					+ ") is not in the atlas";
				return null;
			}
			fontAtlas.DefaultCharacter = value;
		}
		return fontAtlas;
	}

	private static bool ParseGlyph(string line, FontAtlas atlas, out string error)
	{
		error = null;
		string[] array = line.Split(new char[2] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
		if (array.Length != 4)
		{
			error = "a glyph line needs 4 numbers (codepoint advance x y), got " + array.Length.ToString(CultureInfo.InvariantCulture);
			return false;
		}
		int[] array2 = new int[4];
		for (int i = 0; i < 4; i++)
		{
			if (!int.TryParse(array[i], NumberStyles.Integer, CultureInfo.InvariantCulture, out array2[i]))
			{
				error = "'" + array[i] + "' is not a whole number";
				return false;
			}
		}
		if (array2[0] < 0 || array2[0] > 65535)
		{
			error = "codepoint " + array2[0].ToString(CultureInfo.InvariantCulture) + " is out of range";
			return false;
		}
		if (array2[1] <= 0)
		{
			error = "advance must be positive";
			return false;
		}
		if (array2[2] < 0 || array2[3] < 0)
		{
			error = "a texture position cannot be negative";
			return false;
		}
		char c = (char)array2[0];
		if (atlas.Has(c))
		{
			// Two entries for one character is a generator bug; taking the last one silently
			// would hide it behind a glyph that looks almost right.
			error = "character " + array2[0].ToString(CultureInfo.InvariantCulture) + " appears twice";
			return false;
		}
		atlas.Add(c, array2[1], array2[2], array2[3]);
		return true;
	}
}
